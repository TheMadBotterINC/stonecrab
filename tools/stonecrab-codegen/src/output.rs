//! What the generator writes: the provenance header, formatting through the pinned
//! `rustfmt`, the module list, `MANIFEST.toml`, and the replacement of the output set
//! (ADR-0019 decisions 6 and 7).

use std::collections::BTreeMap;
use std::io::Write as _;
use std::path::Path;
use std::process::{Command, Stdio};

use crate::emit::Options;
use crate::{Baseline, Failure, fail};

/// The generator's version: bumped whenever its output changes for an unchanged input.
const VERSION: &str = env!("CARGO_PKG_VERSION");

/// The header every generated `.rs` file begins with (ADR-0019 decision 7).
pub(crate) fn header(baseline: &Baseline) -> String {
    let mut text = format!(
        "// @generated by stonecrab-codegen {VERSION}. DO NOT EDIT; regenerate with `mise run regen`.\n"
    );
    let last = baseline.files.len().saturating_sub(1);
    for (index, file) in baseline.files.iter().enumerate() {
        let options = if index == last {
            " Options: generated/MANIFEST.toml."
        } else {
            ""
        };
        text.push_str("// Source: ");
        text.push_str(&baseline.project);
        text.push(' ');
        text.push_str(&file.upstream_path);
        text.push_str("\n//   at ");
        text.push_str(&baseline.commit);
        text.push_str(" (");
        text.push_str(&baseline.tag);
        text.push_str("),\n//   sha256 ");
        text.push_str(&file.sha256);
        text.push_str(",\n//   vendored as ");
        text.push_str(&file.vendored_path);
        text.push('.');
        text.push_str(options);
        text.push('\n');
    }
    text
}

/// Formats `source` with the `rustfmt` of the pinned toolchain and the repository's
/// `rustfmt.toml`. The header is added afterwards: `rustfmt` leaves alone any file whose
/// first lines say `@generated`.
pub(crate) fn rustfmt(source: &str) -> Result<String, Failure> {
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024", "--config-path", "rustfmt.toml"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .or_else(|error| fail(format!("cannot run rustfmt: {error}")))?;
    let Some(mut stdin) = child.stdin.take() else {
        return fail("rustfmt has no standard input");
    };
    stdin
        .write_all(source.as_bytes())
        .or_else(|error| fail(format!("cannot write to rustfmt: {error}")))?;
    drop(stdin);
    let output = child
        .wait_with_output()
        .or_else(|error| fail(format!("rustfmt did not finish: {error}")))?;
    if !output.status.success() {
        return fail(format!(
            "rustfmt refused the generated code ({}):\n{}\n--- source ---\n{source}",
            output.status,
            String::from_utf8(output.stderr).unwrap_or_default()
        ));
    }
    String::from_utf8(output.stdout).or_else(|error| fail(format!("rustfmt output: {error}")))
}

/// `generated.rs`: one module per type, sorted by name.
pub(crate) fn module_list<'a>(modules: impl Iterator<Item = &'a String>) -> String {
    modules
        .map(|module| format!("pub(super) mod {module};\n"))
        .collect::<Vec<_>>()
        .concat()
}

fn quoted(text: &str) -> String {
    format!("\"{}\"", text.replace('\\', "\\\\").replace('"', "\\\""))
}

fn list(items: impl Iterator<Item = String>) -> String {
    let lines: Vec<String> = items
        .map(|item| format!("  {},\n", quoted(&item)))
        .collect();
    format!("[\n{}]", lines.concat())
}

/// `generated/MANIFEST.toml`: the generator, the upstream baseline, each mspec and the
/// options. No timestamp: git records when.
pub(crate) fn manifest(baseline: &Baseline, options: &Options, options_path: &Path) -> String {
    let mut parts = vec![format!(
        "# @generated by stonecrab-codegen {VERSION}. DO NOT EDIT; regenerate with `mise run regen`.\n\
         # What produced the files beside it (ADR-0019 decision 6). No timestamp: git records when.\n\n\
         [generator]\nname = \"stonecrab-codegen\"\nversion = {}\n\n\
         [upstream]\nproject = {}\ntag = {}\ncommit = {}\n",
        quoted(VERSION),
        quoted(&baseline.project),
        quoted(&baseline.tag),
        quoted(&baseline.commit),
    )];
    for file in &baseline.files {
        parts.push(format!(
            "\n[[mspec]]\nupstream_path = {}\nvendored_path = {}\nsha256 = {}\n",
            quoted(&file.upstream_path),
            quoted(&file.vendored_path),
            quoted(&file.sha256)
        ));
    }
    let path = options_path.to_string_lossy().replace('\\', "/");
    // The byte order is recorded when the options file sets it; absent means `BIG_ENDIAN`.
    let byte_order = options.byte_order.map_or_else(String::new, |order| {
        format!("byte_order = {}\n", quoted(order.keyword()))
    });
    parts.push(format!(
        "\n[options]\nfile = {}\nsupport_module = {}\n{byte_order}types = {}\n\n[options.cases]\n",
        quoted(&path),
        quoted(&options.support_module),
        list(options.types.iter().cloned()),
    ));
    for (type_name, cases) in &options.cases {
        parts.push(format!("{type_name} = {}\n", list(cases.iter().cloned())));
    }
    parts.concat()
}

/// Deletes `generated.rs` and `generated/` under `out` and writes `files` in their place,
/// so a type removed upstream disappears too.
pub(crate) fn replace(out: &Path, files: &BTreeMap<String, String>) -> Result<(), Failure> {
    let directory = out.join("generated");
    if directory.exists() {
        std::fs::remove_dir_all(&directory)
            .or_else(|error| fail(format!("cannot remove {}: {error}", directory.display())))?;
    }
    std::fs::create_dir_all(&directory)
        .or_else(|error| fail(format!("cannot create {}: {error}", directory.display())))?;
    for (name, content) in files {
        let path = out.join(name);
        std::fs::write(&path, content)
            .or_else(|error| fail(format!("cannot write {}: {error}", path.display())))?;
    }
    Ok(())
}
